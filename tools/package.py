#!/usr/bin/env python3
"""Package Translator for Runtipi (runtime.package: source).

Run from anywhere after changing the compose shape:  python3 tools/package.py
The App Manager copies the pinned commit to ${APP_SOURCE_DIR}; the container runs app/server.py from that read-only
copy, so every file in web/ ships as is (the on-device engine's glue is too large for inline packaging).
Writes runtipi/docker-compose.yml. Edit here, never by hand.
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
IMAGE = 'python:3.12-alpine@sha256:c5ba3deef00c7758561a0f03c26f44f10589263d40e732b8748e0d1f38f6dd89'


def main():
    for name in ('app/server.py', 'app/bergamot_models.json', 'openapi.json', 'web/index.html', 'web/device-worker.js'):
        assert (ROOT / name).is_file(), name
    app = {
        'image': IMAGE,
        'user': '1000:1000',
        'working_dir': '/app',
        'command': ['python', '/app/app/server.py'],
        'cap_drop': ['ALL'],
        'security_opt': ['no-new-privileges:true'],
        'read_only': True,
        'mem_limit': '160m',
        'tmpfs': ['/tmp'],
        'init': True,  # Python as PID 1 ignores `docker stop`; Docker's init passes the signal on
        'restart': 'unless-stopped',
        'environment': {
            'PORT': '8799', 'DATA_DIR': '/data', 'PYTHONDONTWRITEBYTECODE': '1', 'PYTHONUNBUFFERED': '1',
            'WIZARD_TRUSTED_HOSTS': '${WIZARD_TRUSTED_HOSTS:-}', 'WIZARD_TRUSTED_ORIGINS': '${WIZARD_TRUSTED_ORIGINS:-}',
            # The App Manager may publish on another host port than 8799: the agent gateway calls that loopback port.
            'WIZARD_APP_HOSTS': '127.0.0.1:${APP_PORT},localhost:${APP_PORT}',
        },
        'volumes': ['${APP_SOURCE_DIR}:/app:ro', '${APP_DATA_DIR}/data:/data'],
        'healthcheck': {'test': ['CMD', 'python', '-c', "import urllib.request;urllib.request.urlopen('http://127.0.0.1:8799/healthz',timeout=3)"],
                        'interval': '15s', 'timeout': '5s', 'retries': 6},
        'x-runtipi': {'is_main': True, 'internal_port': 8799},
        'ports': ['127.0.0.1:${APP_PORT}:8799'],  # loopback only; the Wizard gateway proxies it
    }
    compose = {'services': {'translator': app}, 'x-runtipi': {'schema_version': 2, 'overrides': []}}
    head = '# GENERATED by tools/package.py (runtime.package: source). Edit there.\n'
    (ROOT / 'runtipi/docker-compose.yml').write_text(head + yaml.safe_dump(compose, sort_keys=False, width=100000))
    print('packaged runtipi/docker-compose.yml')


if __name__ == '__main__':
    main()
