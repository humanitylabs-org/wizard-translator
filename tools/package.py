#!/usr/bin/env python3
"""Package Translator: `wam package-inline` for the app container, then add the private LibreTranslate engine.

Run from anywhere after source edits:  python3 tools/package.py
Writes runtipi/docker-compose.yml (portable install) and stage/stack.compose.yml (overlay for a
`wam install-local` developer proof). Both come from ENGINE below: edit here, never by hand.
"""
import os
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
# LibreTranslate v1.9.6, unmodified upstream image (AGPL-3.0), pinned by digest.
ENGINE_IMAGE = 'libretranslate/libretranslate:v1.9.6@sha256:1de2d7056bb8ad607a412f4563d9abe324ff632b43b5be9428bcc8e213aebb32'
# Ten languages keep RAM and disk small; Thai<->English is the must-have pair. Argos ships every one to and from en.
LOAD_ONLY = 'en,th,ja,zh,ko,vi,es,fr,de,ru'
APP_HEALTH = {'test': ['CMD', 'python', '-c', "import urllib.request;urllib.request.urlopen('http://127.0.0.1:8799/healthz',timeout=3)"],
              'interval': '10s', 'timeout': '5s', 'retries': 12}


def engine(models_volume):
    return {
        'image': ENGINE_IMAGE,
        'user': '1000:1000',
        'read_only': True,
        'cap_drop': ['ALL'],
        'security_opt': ['no-new-privileges:true'],
        'tmpfs': ['/tmp', '/app/db:uid=1000,gid=1000'],
        'restart': 'unless-stopped',
        'mem_limit': '2g',
        'environment': {
            'HOME': '/models',                 # Argos keeps downloaded models under $HOME/.local: persisted
            'LT_LOAD_ONLY': LOAD_ONLY,
            'LT_UPDATE_MODELS': 'false',
            'LT_THREADS': '1',                 # one gunicorn worker: one copy of the models in RAM
            'LT_CHAR_LIMIT': '5000',
            'LT_DISABLE_WEB_UI': 'true',
            'LT_DISABLE_FILES_TRANSLATION': 'true',
            'LT_METRICS': 'false',
        },
        'volumes': [models_volume],
        # Never published: only the Translator app reaches it on the app's own network.
        'healthcheck': {'test': ['CMD', '/app/venv/bin/python', '/app/scripts/healthcheck.py'],
                        'interval': '30s', 'timeout': '10s', 'retries': 5, 'start_period': '30m'},
        'depends_on': {'translator': {'condition': 'service_healthy'}},  # the app creates data/models first
    }


def main():
    wam = os.environ.get('WAM') or str(Path(os.environ.get('WIZARD_BUILDER_ROOT', Path.home() / '.wizard-os/builder')) / 'current/bin/wam')
    subprocess.run([wam, 'package-inline', str(ROOT)], check=True, stdout=sys.stderr)
    path = ROOT / 'runtipi/docker-compose.yml'
    compose = yaml.safe_load(path.read_text())
    app = compose['services']['translator']
    app['environment']['ENGINE_URL'] = 'http://translator-engine:5000'
    app['healthcheck'] = APP_HEALTH
    app['restart'] = 'unless-stopped'
    services = {'translator': app, 'translator-engine': engine('${APP_DATA_DIR}/data/models:/models')}
    compose['services'] = services
    head = ('# GENERATED by tools/package.py (wam package-inline + the private LibreTranslate engine). Edit there.\n'
            '# LibreTranslate is the unmodified upstream image (AGPL-3.0), pinned by digest; see NOTICE.md.\n')
    path.write_text(head + yaml.safe_dump(compose, sort_keys=False, width=100000))
    overlay = {'services': {
        'translator': {'environment': {'ENGINE_URL': 'http://translator-engine:5000'}, 'healthcheck': APP_HEALTH,
                       'restart': 'unless-stopped'},
        'translator-engine': engine({'type': 'volume', 'source': 'app-data', 'target': '/models',
                                     'volume': {'subpath': 'models'}}),
    }}
    (ROOT / 'stage').mkdir(exist_ok=True)
    (ROOT / 'stage/stack.compose.yml').write_text(
        '# GENERATED by tools/package.py. Overlay for a `wam install-local` developer proof:\n'
        '#   docker compose -p <project> -f <stage>/compose.yml -f <stage>/source/stage/stack.compose.yml up -d\n'
        + yaml.safe_dump(overlay, sort_keys=False, width=100000))
    print('packaged', path.relative_to(ROOT), 'and stage/stack.compose.yml')


if __name__ == '__main__':
    main()
