#!/usr/bin/env python3
"""Make web/device-worker.js: Mozilla's unmodified bergamot glue (vendor/, MPL-2.0) followed by tools/device-worker.body.js.

One file, so the worker needs no importScripts. Run after changing either input; app/build_view.py checks it is current.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEAD = ("/* GENERATED by tools/build_worker.py. Part 1: vendor/bergamot-translator.js, Mozilla bergamot-translator\n"
        " * v0.6.0+eea6e5a8, MPL-2.0 (https://mozilla.org/MPL/2.0/), unmodified. Part 2: tools/device-worker.body.js (GPL-3.0). */\n")


def build():
    return HEAD + (ROOT / 'vendor/bergamot-translator.js').read_text() + '\n' + (ROOT / 'tools/device-worker.body.js').read_text()


if __name__ == '__main__':
    (ROOT / 'web/device-worker.js').write_text(build())
    print('built web/device-worker.js')
